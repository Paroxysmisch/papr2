pub fn is_pdf_name(name: &str) -> bool {
    matches!(split_name(name), Some((_, Kind::Pdf)))
}

pub fn is_pdf(path: &Path) -> bool {
    path.is_file() && path.file_name().is_some_and(|n| is_pdf_name(&n.to_string_lossy()))
}

/// A file name without its `.pdf`/`.bib` extension.
pub fn title_of(file_name: &str) -> String {
    match split_name(file_name) {
        Some((stem, _)) => stem.to_string(),
        None => file_name.to_string(),
    }
}

/// Whether `stem` is usable as a paper or collection name.
fn valid_stem(stem: &str) -> bool {
    !stem.trim().is_empty()
        && stem.trim() == stem
        && !stem.starts_with('.')
        && !stem.contains(['/', '\\', '\0'])
        && stem.len() <= 240
}

/// Makes arbitrary text safe to use as a paper name.
pub fn sanitize_stem(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| match c {
            c if c.is_whitespace() => ' ',
            '/' | '\\' | '\0' => '-',
            c if c.is_control() => '-',
            c => c,
        })
        .collect();
    let cleaned = cleaned.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut cleaned = cleaned.trim_start_matches('.').trim().to_string();
    // Leave room for " (2).pdf" within common 255-byte file name limits.
    if cleaned.len() > 200 {
        let mut end = 200;
        while !cleaned.is_char_boundary(end) {
            end -= 1;
        }
        cleaned.truncate(end);
        cleaned = cleaned.trim_end().to_string();
    }
    if cleaned.is_empty() {
        "Untitled".to_string()
    } else {
        cleaned
    }
}

fn hash_file(path: &Path) -> Result<String> {
    let mut file = fs::File::open(path).with_context(|| format!("opening {}", path.display()))?;
    let mut hasher = Sha256::new();
    let mut buf = vec![0u8; 64 * 1024];
    loop {
        let n = file.read(&mut buf)?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    Ok(hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect())
}

/// One-time migration from papr2's original storage format
/// (`<data dir>/papr2/library.json` + `papers/<id>.pdf`).
///
/// Files are copied, not moved; the old `library.json` is renamed to
/// `library.json.migrated` so this only runs once.
pub fn migrate_legacy(root: &Path) -> Result<Option<usize>> {
    let Some(legacy) = dirs::data_dir().map(|d| d.join("papr2")) else {
        return Ok(None);
    };
    let index = legacy.join("library.json");
    if !index.exists() {
        return Ok(None);
    }

    #[derive(Deserialize)]
    struct OldPaper {
        id: u64,
        title: String,
        file: String,
    }
    #[derive(Deserialize)]
    struct OldCollection {
        name: String,
        papers: Vec<u64>,
    }
    #[derive(Deserialize)]
    struct OldLibrary {
        papers: Vec<OldPaper>,
        collections: Vec<OldCollection>,
    }

    let old: OldLibrary = serde_json::from_str(&fs::read_to_string(&index)?)
        .with_context(|| format!("parsing {}", index.display()))?;
    let mut library = Library::open(root)?;
    let mut ids = BTreeMap::new();
    for paper in &old.papers {
        let source = legacy.join("papers").join(&paper.file);
        if !source.is_file() {
            continue;
        }
        if let Some(existing) = library.find_duplicate(&source)? {
            ids.insert(paper.id, existing);
            continue;
        }
        let stem = library.unique_stem(&sanitize_stem(&paper.title));
        let dest = library.library_dir().join(format!("{stem}.pdf"));
        library.place_pdf(&source, &dest, Transfer::Copy)?;
        ids.insert(paper.id, stem);
    }
    for collection in &old.collections {
        let name = sanitize_stem(&collection.name);
        fs::create_dir_all(library.collection_dir(&name))?;
        for id in &collection.papers {
            if let Some(paper) = ids.get(id) {
                library.link_paper(&name, paper)?;
            }
        }
    }
    library.refresh()?;
    fs::rename(&index, legacy.join("library.json.migrated"))?;
    Ok(Some(ids.len()))
}

