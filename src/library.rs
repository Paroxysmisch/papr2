//! The research library, stored as plain files and folders.
//!
//! The file system is the source of truth, so everything can also be managed
//! from a file manager or text editor:
//!
//! ```text
//! ~/Documents/papr2/                       (override with PAPR2_HOME)
//!   Library/
//!     Attention Is All You Need.pdf        a paper is a name with a .pdf,
//!     Attention Is All You Need.bib        a .bib (its metadata), or both
//!     BERT.bib                             metadata only: PDF not attached yet
//!   Collections/
//!     Thesis/                              one folder per collection
//!       Attention Is All You Need.pdf -> ../../Library/Attention Is All You Need.pdf
//!       Attention Is All You Need.bib -> ../../Library/Attention Is All You Need.bib
//!       references.bib                     generated by "Export BibTeX"
//!   papr2-cache.toml                       remembers file identities; safe to delete
//! ```
//!
//! Files with the same name (minus extension) in `Library/` are one paper.
//! Collections hold relative symbolic links into `Library/`, never copies.
//! Changes made outside the app are picked up by [`Library::refresh`]:
//!
//! * rename a PDF or .bib in `Library/` → the other file follows; links are repaired
//! * rename a link in a collection      → the paper is renamed everywhere
//! * rename a collection folder         → the collection is renamed
//! * delete a link                      → the paper leaves that collection
//! * delete a paper's files             → the paper is removed, links are cleaned up
//! * put a PDF in `Library/`            → it's added to the library
//! * put a PDF in a collection          → it's moved into `Library/` and linked back
//!
//! The cache remembers each file's identity (inode, size, mtime) so a rename
//! can be told apart from a deletion followed by a new file.

use anyhow::{Context as _, Result, bail};
use serde::{Deserialize, Serialize};
